"""
    MLFMA.FarFields

The far-field representations, the leaf collections built on them, and the kernels that multiply by
them.

Owns `AbstractFarField` and the concrete representation types, their component accessors, the
mirror and coupling rules that are representation-local, the radiation/receive/lazy-receive
collections, and the leaf multiply kernels.

Assembly owns the collection builders. It chooses the collection family, assembler, side, and
storage. Operators owns the store-rule table. Keeping those responsibilities outside this layer
avoids cyclic dependencies between submodules.

Kernels ask operators about their coupling through `Seams`, which declares the generics that
Operators implements.
"""
